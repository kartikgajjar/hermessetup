#!/usr/bin/env python
"""gen.py: generate .claude/agents and .claude/skills from their tracked sources.

Sources: tools/agents/<name>.md (front matter + body; the line '{{SHARED}}' is replaced by
tools/agents/_shared.md) and tools/skills/<name>/SKILL.md (copied as is).
  python tools/gen.py           write the copies
  python tools/gen.py --check   exit 1 when a copy differs from its source (drift)
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import factory_common as fc  # noqa: E402

HEADER = "<!-- GENERATED by tools/gen.py from %s. Do not edit; edit the source and regenerate. -->\n"


def outputs(root: Path) -> dict:
    out = {}
    shared = (root / "tools" / "agents" / "_shared.md").read_text(encoding="utf-8").strip() + "\n"
    for src in sorted((root / "tools" / "agents").glob("*.md")):
        if src.name.startswith("_"):
            continue
        text = src.read_text(encoding="utf-8")
        fm_end = text.index("\n---", 4) + 4
        fm, body = text[:fm_end], text[fm_end:]
        body = body.replace("{{SHARED}}\n", shared)
        out[root / ".claude" / "agents" / src.name] = fm + "\n" + HEADER % src.relative_to(root).as_posix() + body
    for src in sorted((root / "tools" / "skills").glob("*/SKILL.md")):
        rel = src.relative_to(root / "tools" / "skills")
        out[root / ".claude" / "skills" / rel] = src.read_text(encoding="utf-8")
    return out


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    root = fc.repo_root()
    drift = []
    for path, text in outputs(root).items():
        cur = path.read_text(encoding="utf-8") if path.exists() else None
        if "--check" in argv:
            if cur != text:
                drift.append(path.relative_to(root).as_posix())
        elif cur != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print("wrote %s" % path.relative_to(root).as_posix())
    if drift:
        print("DRIFT: %s" % ", ".join(drift), file=sys.stderr)
        return 1
    if "--check" in argv:
        print("generated copies match their sources")
    return 0


if __name__ == "__main__":
    sys.exit(main())
