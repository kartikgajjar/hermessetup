#!/usr/bin/env python
"""profile.py: criticality tier, autonomy level and generated permissions (bootstrap v2.6, 2.8/2.9).

  tier [--facts JSON]            derive the tier from the profile's facts (or the given sample facts)
  level [--tier T --ceiling A --earned A --blocking yes|no]   ceiling, tier cap, earned, working level
  settings [--write | --check]   generate .claude/settings.json from the working level
  propose                        evidence for the next earned level (only the user raises a level)
The profile (config/factory-profile.yaml) is a high-risk file: only the user changes it.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import factory_common as fc  # noqa: E402

HOOK = 'python "$CLAUDE_PROJECT_DIR/tools/hooks/%s"'


def git_rules(sub: str) -> list:
    """Every git rule twice: the plain form and the -C <dir> form (permission rules match text as written)."""
    return ["Bash(git %s)" % sub, "Bash(git %s *)" % sub, "Bash(git -C * %s)" % sub, "Bash(git -C * %s *)" % sub]


def build_settings(root) -> dict:
    lv = fc.level_for_repo(root)
    level = lv["working_off_risk"]
    i = fc.LEVELS.index(level)
    deny = []
    for force in ("push --force", "push -f", "push --force-with-lease"):
        deny += ["Bash(git %s*)" % force, "Bash(git -C * %s*)" % force]
    deny += ["Bash(git push * --force*)", "Bash(git -C * push * --force*)", "Bash(git push * -f*)",
             "Bash(git -C * push * -f*)"]
    for p in (".factory/**", "docs/prd/verdicts/**", "config/**"):
        deny += ["Edit(/%s)" % p, "Write(/%s)" % p]
    deny += ["Bash(python tools/status.py verdict*)"]
    ask = []
    ask += ["Bash(python tools/ship.py*)", "Bash(python tools/dispatch.py integrate*)", "Bash(gh pr merge*)",
            "Bash(gh pr create*)", "Bash(gh api *)", "Bash(gh repo edit*)"]
    if i < 2:  # A0, A1: pushing and merging are the user's steps
        ask += git_rules("push") + git_rules("merge")
    if i < 1:  # A0: committing is the user's step
        ask += git_rules("commit")
    # wait list at every level: live-install mutation, deletion, external pulls
    for s in ("01-cleanup-hermes.ps1", "02-install-hermes-secure.ps1", "04-restore-hermes-state.ps1",
              "10-setup-integrations.ps1", "08-setup-chrome-mcp.ps1", "03-backup-hermes-state.ps1",
              "06-reap-hermes-containers.ps1", "09-watch-mail.ps1"):
        ask += ["Bash(*%s*)" % s, "PowerShell(*%s*)" % s]
    ask += ["Bash(*05-update-hermes.ps1)", "Bash(*05-update-hermes.ps1 -Force*)", "Bash(hermes update*)",
            "Bash(hermes config set*)", "Bash(hermes gateway *)", "Bash(hermes mcp *)", "Bash(docker rm*)",
            "Bash(olk *)", "Bash(curl *)", "Bash(wget *)", "Bash(npm install*)", "Bash(npm audit*)",
            "Bash(npm ci*)", "Bash(git fetch*)", "Bash(git -C * fetch*)", "Bash(git pull*)",
            "Bash(git -C * pull*)", "Bash(git branch -D*)", "Bash(git -C * branch -D*)", "Bash(rm -rf*)",
            "WebFetch", "WebSearch"]
    allow = ["Bash(python tools/status.py*)", "Bash(python tools/profile.py tier*)",
             "Bash(python tools/profile.py level*)", "Bash(python tools/profile.py propose*)",
             "Bash(python tools/profile.py settings --check*)", "Bash(python tools/gate.py*)",
             "Bash(python tools/check.py*)", "Bash(python tools/gen.py --check*)",
             "Bash(python tools/dispatch.py fingerprint*)", "Bash(python tools/dispatch.py verify*)",
             "Bash(python tools/dispatch.py reproof*)", "Bash(python tools/mcp_probe.py*)",
             "Bash(python -m unittest*)", "Bash(npm --prefix chrome-mcp test*)",
             "Bash(pwsh -NoProfile -File *05-update-hermes.ps1 -Plan*)"]
    for sub in ("status", "diff", "log", "show", "branch --show-current", "rev-parse", "worktree list",
                "ls-files", "grep"):
        allow += ["Bash(git %s*)" % sub, "Bash(git -C * %s*)" % sub]
    if i >= 1:
        allow += git_rules("commit")
    hook_cmds = {"guard": HOOK % "guard.py", "stop": HOOK % "stop_guard.py"}
    return {
        "$comment": "Generated by tools/profile.py settings from the working level (%s off risk paths, %s on). "
                    "Do not hand-edit; regenerate and approve." % (lv["working_off_risk"], lv["working_on_risk"]),
        "permissions": {"deny": deny, "ask": ask, "allow": allow},
        "hooks": {
            "PreToolUse": [{"matcher": "Bash|PowerShell|Edit|Write|MultiEdit|NotebookEdit",
                            "hooks": [{"type": "command", "command": hook_cmds["guard"], "timeout": 20}]}],
            "Stop": [{"hooks": [{"type": "command", "command": hook_cmds["stop"], "timeout": 20}]}],
            "SubagentStop": [{"hooks": [{"type": "command", "command": hook_cmds["stop"], "timeout": 20}]}],
        },
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="profile.py", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd")
    s = sub.add_parser("tier")
    s.add_argument("--facts")
    s = sub.add_parser("level")
    s.add_argument("--tier")
    s.add_argument("--ceiling")
    s.add_argument("--earned")
    s.add_argument("--blocking", choices=("yes", "no"))
    s = sub.add_parser("settings")
    g = s.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    sub.add_parser("propose")
    a = ap.parse_args(argv)
    if a.cmd == "tier":
        facts = json.loads(a.facts) if a.facts else fc.profile(fc.repo_root())["facts"]
        print(fc.derive_tier(facts))
        return 0
    if a.cmd == "level":
        if a.tier:
            lv = fc.working_level(a.tier, a.ceiling or "A0", a.earned or "A0", a.blocking == "yes")
        else:
            lv = fc.level_for_repo(fc.repo_root())
        print("ceiling %(ceiling)s | tier %(tier)s cap %(cap_off_risk)s off risk / %(cap_on_risk)s on risk | "
              "earned %(earned)s | working %(working_off_risk)s off risk / %(working_on_risk)s on risk" % lv)
        return 0
    if a.cmd == "settings":
        root = fc.repo_root()
        text = json.dumps(build_settings(root), indent=2) + "\n"
        target = Path(root) / ".claude" / "settings.json"
        if a.write:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
            print("wrote %s" % target)
            return 0
        if a.check:
            cur = target.read_text(encoding="utf-8") if target.exists() else ""
            if cur != text:
                print("DRIFT: .claude/settings.json differs from the generated permissions", file=sys.stderr)
                return 1
            print("settings.json matches the working level")
            return 0
        print(text)
        return 0
    if a.cmd == "propose":
        root = fc.repo_root()
        lv = fc.level_for_repo(root)
        print("earned now: %s. Only the user raises it: confirm, record a U<n>, edit the profile, then "
              "python tools/profile.py settings --write." % lv["earned"])
        import subprocess
        subprocess.run([sys.executable, str(HERE / "status.py"), "measures"], cwd=root)
        return 0
    ap.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())
